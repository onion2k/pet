const MISSING = '###/#.#/#.#/#.#/###'

export function glyph(ch: string): string[] {
  return (G[ch.toUpperCase()] ?? MISSING).split('/')
}

/** Width in pixels of a string rendered at scale 1, excluding the trailing gap. */
export function textWidth(text: string, scale = 1): number {
  if (text.length === 0) return 0
  return (text.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP) * scale
}
